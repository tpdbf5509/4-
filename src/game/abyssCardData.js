// 보기 좋은 수 — 소수 둘째 자리까지, 뒤 0 은 뗀다
export function fmt(v) { return String(Math.round(v * 100) / 100); }
// 다이아 값에서 브론즈 · 골드 값 — 5 이상은 정수, 그 아래는 0.1 단위
export function tierVal(d, t) {
  if (t >= 3) return d;
  const x = d * TIER_MUL[t - 1];
  const step = d >= 5 ? 1 : 0.1;
  return Math.max(step, Math.round(x / step) * step);
}

export const CARDS = RAW.map(([n, name, d, text, opt = {}]) => {
  const cat = CARD_CATS.find((c) => n >= c.from && n <= c.to);
  const tv = opt.tv || [1, 2, 3].map((t) => Math.round(tierVal(d, t) * 100) / 100);
  return { n, name, cat: cat.id, catName: cat.name, curse: isCurse(n), tv, text, jobs: opt.jobs || null, note: opt.note || "" };
});
export const CARD_BY_N = Object.fromEntries(CARDS.map((c) => [c.n, c]));

// 그 등급의 글 — tier 1~3
export function cardText(n, tier) {
  const c = CARD_BY_N[n];
  if (!c) return "";
  const v = c.tv[Math.max(1, Math.min(3, tier)) - 1];
  if (typeof c.text === "function") return c.text(v);
  return c.text.split("{v}").join(Array.isArray(v) ? v.map(fmt).join("/") : fmt(v));
}
