export const storyGuideOf = (s) => (s ? STORY_GUIDE[s.q] || null : null);

// 조건 붙은 문장 묶음에서 지금 꼬리표에 맞는 것만 잇는다 — 문자열 하나 또는 [{t, if, not}]
const textOf = (v, tags) => (!v ? '' : typeof v === 'string' ? v : v.filter((l) => storyLineShown(l, tags, {})).map((l) => l.t).join(' '));

/* 알게 된 것 — 대상 하나와 이야기를 마쳤을 때. 대상 몫(단계 id/대상 id)과, 단계를 다 마쳤을 때의 단계 몫(단계 id) */
export function storyFact(s, id, tags = [], stepDone = true) {
  if (!s) return '';
  return [textOf(STORY_FACTS[`${s.id}/${id}`], tags), stepDone ? textOf(STORY_FACTS[s.id], tags) : ''].filter(Boolean).join(' ');
}

const TRUST_WORD = {2: '깊이 믿음', 1: '믿음', 0: '보통', '-1': '서먹함', '-2': '불신'};
const PEOPLE_NAME = {mina: '미나', zero: '제로', sera: '세라', irion: '이리온', kael: '카엘', hangyeol: '한결'};

/* 이야기 기록 — 퀘스트 창에서 장마다 본다. sq = 가방 bag.sq
   끝낸 장: 요약 · 확인한 사실 · 남은 의문(풀렸으면 답) · 관계 변화 · 다음 장 연결. 진행 중인 장: 지금까지 확인한 사실만 */
export function storyJournal(sq) {
  const i = Math.max(0, Number(sq?.i) || 0), n = sq?.n || [], tags = sq?.c || [];
  const cur = STORY_STEPS[i];
  const doneCh = cur ? cur.ch - 1 : 30;
  const lastCh = cur ? cur.ch : 30;
  const chapters = [];
  for (let ch = 1; ch <= lastCh; ch++) {
    const facts = [];
    STORY_STEPS.forEach((s, k) => {
      if (s.ch !== ch || k > i) return;
      const ids = k < i ? stepTargets(s) : stepTargets(s).filter((x) => n.includes(x));
      ids.forEach((id) => { const f = textOf(STORY_FACTS[`${s.id}/${id}`], tags); if (f) facts.push(f); });
      if (k < i) { const f = textOf(STORY_FACTS[s.id], tags); if (f) facts.push(f); }
    });
    const r = STORY_RECAP[ch] || {}, done = ch <= doneCh;
    chapters.push({
      ch, name: STORY_CHAPTERS[ch], part: partOf(ch).n, done, facts,
      sum: done ? r.sum || '' : '',
      open: done ? (r.open || []).map((o) => ({q: o.q, a: o.by && doneCh >= o.by ? o.a : ''})) : [],
      bond: done ? (r.bond || []).filter((l) => storyLineShown(l, tags, {})).map((l) => l.t) : [],
      next: done ? r.next || '' : '',
    });
  }
  const trust = TRUST_PEOPLE.filter((k) => sq?.t?.[k]).map((k) => ({id: k, name: PEOPLE_NAME[k], v: sq.t[k], word: TRUST_WORD[sq.t[k]] || ''}));
  return {doneCh, chapters: chapters.reverse(), trust};
}

/* 마을 분위기 — 이야기를 진행하면 에르덴 주민이 그 사건 뒤의 말을 한다(storyRecap.js STORY_MOOD).
   기록관 소은은 마지막으로 끝낸 장을 정리해 준다(다시 접속해 앞 이야기를 잊은 사람을 위해). 없으면 null */
const MOOD_AT = Object.fromEntries(STORY_MOOD.map((m) => [m.after, STORY_STEPS.findIndex((s) => s.id === m.after)]));
export function storyMoodFor(npcId, sq) {
  const i = Math.max(0, Number(sq?.i) || 0), tags = sq?.c || [];
  if (npcId === 'dawn-archivist') {
    const ch = (STORY_STEPS[i]?.ch || 31) - 1;
    const r = STORY_RECAP[ch];
    if (!r) return null;
    return [`${ch}장 「${STORY_CHAPTERS[ch]}」까지 정리해 두었어요.`, r.sum, `다음은 이렇게 이어져요. ${r.next}`, '자세한 건 의뢰 · 퀘스트 창의 「이야기 기록」에 적어 두었어요.'];
  }
  const hit = STORY_MOOD.filter((m) => m.npc === npcId && MOOD_AT[m.after] >= 0 && i > MOOD_AT[m.after]).at(-1);
  if (!hit) return null;
  const lines = hit.lines.map((l) => (typeof l === 'string' ? {t: l} : l)).filter((l) => storyLineShown(l, tags, {})).map((l) => l.t);
  return lines.length ? lines : null;
}
